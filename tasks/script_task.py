def iter_script_insert_items() -> List[Dict[str, Any]]:
    items: List[Dict[str, Any]] = []
    seen_names = set()
    for group in SCRIPT_INSERT_GROUPS:
        for item in group.get("items") or ():
            if not isinstance(item, dict) or not str(item.get("snippet") or "").strip():
                continue
            name = str(item.get("name") or "").strip()
            if not name or name in seen_names:
                continue
            seen_names.add(name)
            items.append(item)
    return items


# 从插入目录签名里抽取“名字(...)”调用路径的正则，与测试用例保持同一份，
# 供生产（命令补全同步）与测试（目录/文档一致性）共用，避免手工维护漂移。
_CATALOG_CALL_RE = re.compile(
    r"(?<![\w一-鿿])([A-Za-z_一-鿿][\w一-鿿]*(?:\.[A-Za-z_一-鿿][\w一-鿿]*)*)\s*\("
)


def script_catalog_call_paths(include_result_methods: bool = True) -> List[str]:
    """返回插入目录里所有命令/命名空间方法的调用路径（去重、保持出现顺序）。

    忽略 ``子程序``/``函数`` 这类“声明”条目（其括号里的标识符是用户自定义名字，
    不是命令）。``include_result_methods=False`` 时进一步剔除结果对象方法
    （``点``/``随机点`` 这类以结果变量点出来的方法），只留独立命令，供命令补全
    同步与文档一致性检查使用。
    """
    from task_workflow.script_sandbox import _RESULT_METHODS

    paths: List[str] = []
    for item in iter_script_insert_items():
        if str(item.get("name") or "").strip() in {"子程序", "函数"}:
            continue
        for path in _CATALOG_CALL_RE.findall(str(item.get("signature") or "")):
            if not include_result_methods and path.split(".")[-1] in _RESULT_METHODS:
                continue
            if path not in paths:
                paths.append(path)
    return paths


