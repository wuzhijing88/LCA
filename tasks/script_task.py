def _match_paren(text: str, open_index: int) -> Optional[int]:
    depth = 0
    quote = None
    escape = False
    for index in range(open_index, len(text)):
        char = text[index]
        if quote:
            if escape:
                escape = False
            elif char == "\\":
                escape = True
            elif char == quote:
                quote = None
            continue
        if char in {'"', "'"}:
            quote = char
            continue
        if char == "(":
            depth += 1
            continue
        if char == ")":
            depth -= 1
            if depth == 0:
                return index
    return None


def _split_args_spans(text: str, start: int, end: int) -> List[Tuple[int, int, str]]:
    args: List[Tuple[int, int, str]] = []
    buf_start = start
    depth = 0
    quote = None
    escape = False
    for index in range(start, end):
        char = text[index]
        if quote:
            if escape:
                escape = False
            elif char == "\\":
                escape = True
            elif char == quote:
                quote = None
            continue
        if char in {'"', "'"}:
            quote = char
            continue
        if char in "([{":
            depth += 1
            continue
        if char in ")]}":
            depth = max(0, depth - 1)
            continue
        if char == "," and depth == 0:
            token = text[buf_start:index].strip()
            if token:
                lead = 0
                while buf_start + lead < index and text[buf_start + lead] in {" ", "\t"}:
                    lead += 1
                args.append((buf_start + lead, buf_start + lead + len(token), token))
            buf_start = index + 1
    token = text[buf_start:end].strip()
    if token:
        lead = 0
        while buf_start + lead < end and text[buf_start + lead] in {" ", "\t"}:
            lead += 1
        args.append((buf_start + lead, buf_start + lead + len(token), token))
    return args


